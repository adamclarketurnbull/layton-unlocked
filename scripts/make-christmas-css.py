#!/usr/bin/env python3
"""Builds src/css/christmas.css (the classic Christmas theme) from src/css/style.css.

Run it from the repo root:  python3 scripts/make-christmas-css.py
Re-run it after any change to style.css so the Christmas version stays in step.

The theme is switched on and off with "christmas": true / false in src/_data/site.json.
"""
import re, urllib.parse, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src/css/style.css"
OUT = ROOT / "src/css/christmas.css"

HEXES = {
 '#2B1400':'#12392B','#4FD6B5':'#7CC28F','#FF6B4A':'#E5534B','#FFC247':'#F2C14E','#F0E4CD':'#FBF4E6','#8A7458':'#6E7F72',
 '#241443':'#12392B','#1A1225':'#0B2A20','#150A1F':'#082018','#0E2C27':'#12392B','#F0388B':'#E5534B','#FFD166':'#F2C14E',
 '#C4292A':'#B3262B','#FFF6E3':'#FFFBF2','#FFE8D1':'#F6E7D4','#F2E9CE':'#F3ECD6','#EADFC1':'#E9E0C6','#3A2A5C':'#1F5A44','#FF8A3D':'#F2C14E'}
RGB = {'43,20,0':'18,57,43','79,214,181':'124,194,143','255,107,74':'229,83,75','26, 18, 37':'11,42,32',
       '36, 20, 67':'18,57,43','14,44,39':'18,57,43','255,138,92':'229,83,75'}
HERO = 'linear-gradient(180deg,rgba(11,42,32,.55),rgba(11,42,32,.28) 45%,rgba(60,15,15,.6))'
BAUBLE_COLOURS = ['#D63A3A', '#E8B84A', '#2E8B57', '#F4F1EA']
WIRE = '#7a5b2e'
W, H = 400, 72

def ycurve(x):
    t = (x % 200) / 200
    return (1-t)**2*3 + 2*t*(1-t)*30 + t*t*3

def garland():
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">',
             f'<path d="M0 3 Q100 30 200 3 Q300 30 400 3" fill="none" stroke="{WIRE}" stroke-width="2" stroke-linecap="round"/>']
    for i, x in enumerate([28,70,112,154,228,270,312,354]):
        y = ycurve(x); c = BAUBLE_COLOURS[i % len(BAUBLE_COLOURS)]
        parts.append(f'<rect x="{x-3}" y="{y:.1f}" width="6" height="6" rx="1" fill="#E8B84A"/>')
        parts.append(f'<circle cx="{x}" cy="{y+16:.1f}" r="10" fill="{c}"/>')
        parts.append(f'<circle cx="{x-3.5}" cy="{y+12.5:.1f}" r="3" fill="#fff" opacity=".55"/>')
        parts.append(f'<rect x="{x-9}" y="{y+14:.1f}" width="18" height="2.4" fill="#fff" opacity=".25"/>')
    parts.append('</svg>')
    return 'url("data:image/svg+xml,' + urllib.parse.quote(''.join(parts), safe="/:=\'(), ") + '")'

css = SRC.read_text(encoding='utf-8')
for a, b in HEXES.items():
    css = re.sub(re.escape(a), b, css, flags=re.I)
for a, b in RGB.items():
    css = css.replace(a, b)
css = ("/* GENERATED by scripts/make-christmas-css.py from style.css. Do not edit by hand. */\n" + css +
  f"\n/* Christmas extras */\n.hero::before{{background:{HERO}!important}}\n"
  f".ev-hero{{padding-top:96px!important}}\n.link-green,.link-green:visited{{color:#12392B!important;text-decoration:underline;font-weight:800}}\n"
  f".nav::after{{content:\"\";position:absolute;left:0;right:0;top:100%;height:{H}px;background:{garland()} repeat-x 0 0;pointer-events:none;z-index:5}}\n"
  f".nav:has(.nav__toggle-input:checked)::after{{display:none}}\n")
OUT.write_text(css, encoding='utf-8')
print("wrote", OUT, len(css), "bytes")
